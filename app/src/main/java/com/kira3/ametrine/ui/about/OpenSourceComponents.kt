/**
 * Something the APK contains that someone else wrote, with the license it is used under.
 *
 * [files] are under `assets/licenses/`: emucore's `collectCoreLicenses` copies them from the
 * aegirine-core tree and from the prebuilt libraries, and the app keeps the plain license texts
 * (MIT, zlib, OFL and others) for parts whose tree has none. [notice] is the copyright line for
 * those, shown above the text.
 */
data class OpenSourceComponent(
    val id: String,
    val name: String,
    val license: String,
    val url: String,
    val files: List<String>,
    val notice: String? = null,
)

enum class ComponentGroup(@param:StringRes val title: Int) {
    Core(R.string.licenses_group_core),
    Native(R.string.licenses_group_native),
    Assets(R.string.licenses_group_assets),
    Android(R.string.licenses_group_android),
}

